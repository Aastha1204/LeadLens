// Embeds sql/*.sql into src/lib/sql/generated.ts so the trace drawer can show the exact SQL.
import fs from "node:fs";

const read = (f) => fs.readFileSync(new URL(`../sql/${f}`, import.meta.url), "utf8");
const views = {};
for (const block of read("views.sql").split(/^-- @view /m).slice(1)) {
  const nl = block.indexOf("\n");
  views[block.slice(0, nl).trim()] = block.slice(nl + 1).trim();
}
const out = `// AUTO-GENERATED by scripts/gen-sql.mjs from sql/*.sql. Do not edit.
export const SQL_SCHEMA = ${JSON.stringify(read("schema.sql"))};
export const SQL_RLS = ${JSON.stringify(read("rls.sql"))};
export const SQL_VIEWS_ALL = ${JSON.stringify(read("views.sql"))};
export const SQL_VIEWS: Record<string, string> = ${JSON.stringify(views, null, 2)};
`;
fs.writeFileSync(new URL("../src/lib/sql/generated.ts", import.meta.url), out);
console.log("sql generated:", Object.keys(views).join(", "));
